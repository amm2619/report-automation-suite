'use strict';

/*
 * Offline build: compile the JSX sources into a single bundle.js so the app
 * runs with no CDN and no in-browser Babel — just open index.html.
 *
 *   npm install && npm run build
 *
 * Sources stay authoritative; bundle.js is generated. Re-run after editing any
 * .jsx file or data.js.
 */

const fs = require('fs');
const path = require('path');
const babel = require('@babel/core');

const root = __dirname;
// Plain JS prepended as-is (no JSX); then the compiled JSX. Dependency order.
const PLAIN = ['data.js', 'fsstore.js'];
const JSX = ['ui.jsx', 'panel.jsx', 'planner.jsx', 'team.jsx', 'views.jsx', 'app.jsx'];

function compile(file) {
  return babel.transformSync(fs.readFileSync(path.join(root, file), 'utf8'), {
    sourceType: 'script',
    presets: [['@babel/preset-react', { runtime: 'classic' }]],
    filename: file,
    compact: false,
    comments: false,
  }).code;
}

const parts = [
  '/* GENERATED by build.js — do not edit directly.',
  '   Edit the .jsx / .js sources and run `npm run build`. */',
];
for (const f of PLAIN) {
  parts.push(`/* ===== ${f} ===== */`);
  parts.push(fs.readFileSync(path.join(root, f), 'utf8'));
}
for (const f of JSX) {
  parts.push(`/* ===== ${f} ===== */`);
  parts.push(compile(f));
}

fs.writeFileSync(path.join(root, 'bundle.js'), parts.join('\n\n') + '\n');
console.log(`Wrote bundle.js (${PLAIN.length} plain + ${JSX.length} JSX sources)`);
